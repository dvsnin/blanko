func sortPreset(key, name, desc, topic, glyph string, ages []string, task string, items []Card, zoneNames ...string) Preset {
	return Preset{Key: key, Name: name, Description: desc, Topic: topic, Ages: ages, Duration: 20, Glyph: glyph, Build: func(d *Doc) {
		f := lesson(d, name, task)
		cols := 8
		cardGrid(d, f, 40, contentY, 165, 160, 20, cols, items, "")
		rows := (len(items) + cols - 1) / cols
		top := contentY + float64(rows)*180 + 10
		n := float64(len(zoneNames))
		w := (frameW - 80 - 40*(n-1)) / n
		zones(d, f, 40, top, w, frameH-top-30, 40, zoneNames...)
	}}
}

