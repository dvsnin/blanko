// sequencePreset - картинки-шаги вразброс и пронумерованные слоты: собрать правильный порядок.
func sequencePreset(key, name, desc, topic, glyph string, ages []string, task string, steps []Card) Preset {
	return Preset{Key: key, Name: name, Description: desc, Topic: topic, Ages: ages, Duration: 15, Glyph: glyph, Build: func(d *Doc) {
		f := lesson(d, name, task)
		n := len(steps)
		w := (frameW - 80 - 20*float64(n-1)) / float64(n)
		cardRow(d, f, 40, contentY, w, 200, 20, steps, "")
		slots(d, f, 40, 520, w, 240, 20, n)
	}}
}

